type PluralBase<Key extends string> = Key extends `${infer Base}_${"one" | "other"}` ? Base : never;
type ExtraPluralKey<T> = `${PluralBase<Extract<keyof T, string>>}_${"zero" | "two" | "few" | "many"}`;

export type TranslationShape<T> = {
  [K in keyof T]: T[K] extends string ? string : TranslationShape<T[K]>
} & {
  [K in ExtraPluralKey<T>]?: string
};
export type ToolGroupKey = keyof typeof en.toolbar.groups;
